#ifndef ESP32C3_GPIO_REGS_H
#define ESP32C3_GPIO_REGS_H

#include <stdint.h>

// Base Addresses
#define GPIO_BASE_ADDR						0x60004000U
#define IO_MUX_BASE_ADDR					0x60009000U



// Offsets
#define GPIO_PIN_REG_OFFSET					0x0074U

#define GPIO_OUT_W1TS_REG_OFFSET			0x0008U
#define GPIO_OUT_W1TC_REG_OFFSET			0x000CU

#define GPIO_ENABLE_W1TS_REG_OFFSET			0x0024U
#define GPIO_ENABLE_W1TC_REG_OFFSET			0x0028U

#define GPIO_FUNC_IN_SEL_CFG_REG_OFFSET		0x0154U
#define GPIO_FUNC_OUT_SEL_CFG_REG_OFFSET	0x0554U

#define GPIO_IN_REG_OFFSET					0x003CU
#define GPIO_OUT_REG_OFFSET					0x0004U

#define GPIO_ENABLE_REG_OFFSET				0x0020U

#define IO_MUX_GPIO_REG_OFFSET				0x0004U



// GPIO_FUNCn_IN_SEL_CFG_REG Field Positions
#define GPIO_FUNC_IN_SEL_FIELDPOS			0U
#define GPIO_SIG_IN_SEL_FIELDPOS			6U

// GPIO_PINn_REG Field Positions
#define GPIO_PIN_SYNC2_BYPASS_FIELDPOS		0U
#define GPIO_PIN_SYNC1_BYPASS_FIELDPOS		3U
#define GPIO_PIN_PAD_DRIVER_FIELDPOS		2U

// GPIO_ENABLE_W1TS_REG Field Positions
#define GPIO_ENABLE_W1TS_FIELDPOS			0U

// GPIO_ENABLE_W1TC_REG Field Positions
#define GPIO_ENABLE_W1TC_FIELDPOS			0U

// GPIO_FUNCn_OUT_SEL_CFG_REG Field Positions
#define GPIO_FUNC_OUT_SEL_FIELDPOS			0U
#define GPIO_FUNC_OEN_SEL_FIELDPOS			9U

// IO_MUX_GPIOn_REG Field Positions
#define IO_MUX_GPIO_FILTER_EN_FIELDPOS		15U
#define IO_MUX_GPIO_FUN_IE_FIELDPOS			9U
#define IO_MUX_GPIO_FUN_WPU_FIELDPOS		8U
#define IO_MUX_GPIO_FUN_WPD_FIELDPOS		7U
#define IO_MUX_GPIO_MCU_SEL_FIELDPOS		12U
#define IO_MUX_GPIO_FUN_DRV_FIELDPOS		10U

// GPIO_IN_REG Field Positions
#define GPIO_IN_DATA_NEXT_FIELDPOS			0U

// GPIO_OUT_REG Field Positions
#define GPIO_OUT_DATA_ORIG_FIELDPOS			0U

// GPIO_ENABLE_REG Field Positions
#define GPIO_ENABLE_DATA_FIELDPOS			0U



// GPIO_FUNCn_IN_SEL_CFG_REG Bitmasks
#define GPIO_FUNC_IN_SEL_MASK				(31U << GPIO_FUNC_IN_SEL_FIELDPOS)

// GPIO_PINn_REG Bitmasks
#define GPIO_PIN_SYNC1_BYPASS_MASK			(3U << GPIO_PIN_SYNC1_BYPASS_FIELDPOS)
#define GPIO_PIN_SYNC2_BYPASS_MASK			(3U << GPIO_PIN_SYNC2_BYPASS_FIELDPOS)

// GPIO_IN_REG Bitmask
#define GPIO_IN_DATA_NEXT_MASK				(4194303U << GPIO_IN_DATA_NEXT_FIELDPOS)

// GPIO_OUT_REG Bitmask
#define GPIO_OUT_DATA_ORIG_MASK				(4194303U << GPIO_OUT_DATA_ORIG_FIELDPOS)

// GPIO_ENABLE_W1TS_REG Bitmas
#define GPIO_ENABLE_W1TS_MASK				(4194303U << GPIO_ENABLE_W1TS_FIELDPOS)

// GPIO_ENABLE_W1TC_REG Bitmask
#define GPIO_ENABLE_W1TC_MASK				(4194303U << GPIO_ENABLE_W1TC_FIELDPOS)

// GPIO_FUNC_OUT_SEL_CFG_REG Bitmask
#define GPIO_FUNC_OUT_SEL_MASK				(255U << GPIO_FUNC_OUT_SEL_FIELDPOS)
#define GPIO_FUNC_OEN_SEL_MASK				(1U << GPIO_FUNC_OEN_SEL_FIELDPOS)

// IO_MUX_GPIO_REG Bitmask
#define IO_MUX_GPIO_FUN_IE_MASK				(1U << IO_MUX_GPIO_FUN_IE_FIELDPOS)
#define IO_MUX_GPIO_FUN_WPU_MASK			(1U << IO_MUX_GPIO_FUN_WPU_FIELDPOS)
#define IO_MUX_GPIO_FUN_WPD_MASK			(1U << IO_MUX_GPIO_FUN_WPD_FIELDPOS)
#define IO_MUX_GPIO_MCU_SEL_MASK			(7U << IO_MUX_GPIO_MCU_SEL_FIELDPOS)
#define IO_MUX_GPIO_FUN_DRV_MASK			(3U << IO_MUX_GPIO_FUN_DRV_FIELDPOS)

// GPIO_ENABLE_REG Bitmask
#define GPIO_ENABLE_DATA_MASK				(4194303U << GPIO_ENABLE_DATA_FIELDPOS)



// Register Config-Set
#define REG32(addr)							(*(volatile uint32_t *)(uintptr_t)(addr))

// IO MUX
#define IO_MUX_GPIOn_REG(n)					REG32(IO_MUX_BASE_ADDR + (IO_MUX_GPIO_REG_OFFSET + (4U* (n))))

// GPIO_PINn_REG
#define GPIO_PINn_REG(n)					REG32(GPIO_BASE_ADDR + GPIO_PIN_REG_OFFSET + (4U * (n)))

// Input
#define GPIO_FUNCn_IN_SEL_CFG_REG(n)		REG32(GPIO_BASE_ADDR + GPIO_FUNC_IN_SEL_CFG_REG_OFFSET + (4U * (n)))
#define GPIO_IN_REG							REG32(GPIO_BASE_ADDR + GPIO_IN_REG_OFFSET)

// Output
#define GPIO_FUNCn_OUT_SEL_CFG_REG(n)		REG32(GPIO_BASE_ADDR + GPIO_FUNC_OUT_SEL_CFG_REG_OFFSET + (4U * (n)))
#define GPIO_ENABLE_REG						REG32(GPIO_BASE_ADDR + GPIO_ENABLE_REG_OFFSET)
#define GPIO_OUT_REG						REG32(GPIO_BASE_ADDR + GPIO_OUT_REG_OFFSET)
#define GPIO_OUT_W1TS_REG					REG32(GPIO_BASE_ADDR + GPIO_OUT_W1TS_REG_OFFSET)
#define GPIO_OUT_W1TC_REG					REG32(GPIO_BASE_ADDR + GPIO_OUT_W1TC_REG_OFFSET)
#define GPIO_ENABLE_W1TS_REG				REG32(GPIO_BASE_ADDR + GPIO_ENABLE_W1TS_REG_OFFSET)
#define GPIO_ENABLE_W1TC_REG				REG32(GPIO_BASE_ADDR + GPIO_ENABLE_W1TC_REG_OFFSET)


#endif